while True:
    n = int(input("Введіть число: "))

    if n > 100:
        print(f"Число {n} більше 100 → зупиняємо зчитування.")
        break

    if n < 10:
        print(f"Число {n} менше 10 → пропускаємо.")
        continue

    print(f"Число {n} підходить (10 ≤ n ≤ 100) → виводимо.")